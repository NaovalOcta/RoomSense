async page => {
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const evidence = [];
  await page.context().route('**/*', route => {
    const host = new URL(route.request().url()).hostname;
    return ['127.0.0.1', 'localhost'].includes(host) ? route.continue() : route.abort();
  });
  if (page.routeWebSocket) await page.routeWebSocket(/.*/, ws => ws.close());
  const cdp = await page.context().newCDPSession(page);
  await cdp.send('Emulation.setTimezoneOverride', {timezoneId: 'America/Los_Angeles'});
  await page.goto('http://127.0.0.1:8093/book');
  const dateInput = page.locator('#date');
  const min = await dateInput.getAttribute('min');
  const max = await dateInput.getAttribute('max');
  check((Date.parse(max)-Date.parse(min))/86400000 === 14, 'date bounds');
  check(await page.locator('#start_time').getAttribute('step') === '300', 'five-minute grid');
  check(await page.locator('#start_time').getAttribute('min') === '07:00', 'opening hour');
  check(await page.locator('#end_time').getAttribute('max') === '21:00', 'closing hour');
  const date = new Date(Date.parse(min+'T12:00:00Z')+86400000).toISOString().slice(0,10);
  const room = await page.locator('#room_id option').filter({hasText: 'WIB Browser Room'}).getAttribute('value');
  await page.locator('#room_id').selectOption(room);
  await dateInput.fill(date);
  await page.locator('#purpose').fill('WP07 browser round trip');
  const invalid = await page.evaluate(async ({room,date}) => {
    const response = await fetch('/book', {method:'POST', headers:{'Content-Type':'application/json','Accept':'application/json','X-CSRF-TOKEN':document.querySelector('meta[name="csrf-token"]').content}, body:JSON.stringify({room_id:room,date,start_time:'08:00:01',end_time:'10:00'})});
    return {status:response.status,body:await response.json()};
  }, {room,date});
  check(invalid.status===422 && invalid.body.errors.start_time, 'invalid direct request feedback');
  evidence.push('Browser-origin malformed time POST: 422 with start_time error');
  await page.locator('#end_time').fill('08:25');
  await page.locator('#booking-form').evaluate(form => form.submit());
  const error = page.locator('#end_time').locator('..').locator('p.text-red-400');
  await error.waitFor();
  check((await error.innerText()).includes('30–240'), 'server duration validation feedback');
  evidence.push('25-minute duration rejected by server with visible field feedback');
  await page.locator('#end_time').fill('10:00');
  await page.getByRole('button', {name:'Submit Booking Request'}).click();
  await page.waitForURL('**/dashboard');
  const history = await page.locator('main').innerText();
  check(history.includes('WP07 browser round trip') && history.includes('8:00 AM') && history.includes('10:00 AM'), 'history round trip');
  await page.screenshot({path:'D:/Documents/Artifact Documentation Project/Room Sense/v11-browser-history.png',fullPage:true});
  const schedule = await page.evaluate(async ({room,date}) => (await fetch(`/api/rooms/${room}/schedule?date=${date}`)).json(),{room,date});
  check(schedule.bookings[0].start==='08:00' && schedule.bookings[0].end==='10:00', 'WIB schedule');
  evidence.push('Create booking and history/schedule: 08:00–10:00 WIB, browser timezone America/Los_Angeles');
  await page.goto('http://127.0.0.1:8093/notifications');
  await page.locator('[data-notification-detail]').first().click();
  await page.getByText('Current booking #', {exact:false}).waitFor();
  check((await page.locator('body').innerText()).includes('08:00'), 'notification WIB details');
  await page.screenshot({path:'D:/Documents/Artifact Documentation Project/Room Sense/v11-browser-notification.png',fullPage:true});
  evidence.push('Notification details show current booking WIB time');
  await page.goto('http://127.0.0.1:8093/rooms');
  await page.locator('[name=search]').fill('😀');
  await page.locator('[name=capacity]').selectOption('50');
  await page.locator('form').filter({has:page.locator('[name=search]')}).locator('button[type=submit]').click();
  let catalog = await page.locator('main').innerText();
  check(catalog.includes('WIB Browser Room') && !catalog.includes('Small Browser Room') && !catalog.includes('Inactive Browser Room'), 'search and capacity');
  await page.getByRole('link',{name:'Clear',exact:true}).click();
  catalog = await page.locator('main').innerText();
  check(catalog.includes('WIB Browser Room') && catalog.includes('Small Browser Room') && !catalog.includes('Inactive Browser Room'), 'clear search');
  evidence.push('Unicode search + capacity filter + Clear passed, inactive excluded');
  await page.locator('[name=search]').fill('a'.repeat(101));
  await page.locator('form').filter({has:page.locator('[name=search]')}).locator('button[type=submit]').click();
  check((await page.locator('main').innerText()).includes('100'), 'search length feedback');
  evidence.push('101-code-point search rejected with visible feedback');
  return {status:'PASS',checks:evidence,date,room,deviceTimezone:'America/Los_Angeles'};
}
